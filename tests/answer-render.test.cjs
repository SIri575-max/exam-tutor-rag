const assert=require('node:assert/strict');
globalThis.katex=require('../assets/katex/katex.min.js');
globalThis.MathView=require('../math-render.js');
const view=require('../answer-render.js');
let checks=0;
function check(condition,message){assert(condition,message);checks++}
let html=view.render('### 似然函数\n\n**参数范围**为 $\\theta \\ge 4$。\n\n- 核对样本\n- 求最大值');
check(html.includes('<h3>似然函数</h3>'),'headings should be compiled');
check(html.includes('<strong>参数范围</strong>'),'bold should be compiled');
check(html.includes('class="katex"'),'inline math must still compile');
check(html.includes('<ul>')&&html.includes('<li>核对样本</li>'),'lists should be structural');
check(!html.includes('###')&&!html.includes('**'),'no raw supported Markdown remains');
html=view.render('$$\n\\hat{\\theta}=\\max_i X_i\n$$\n\n1. 条件\n2. 结论');
check(html.includes('katex-display'),'multiline display math compiles');
check(html.includes('<ol>')&&!html.includes('math-fallback'),'ordered list does not corrupt display math');
html=view.render('| 项目 | 公式 |\n| --- | --- |\n| 后验 | $\\mathrm{Beta}(5,6)$ |\n| 绝对值 | $|x|$ |');
check(html.includes('<table>')&&html.includes('<thead>'),'Markdown table should become a table');
check((html.match(/<td>/g)||[]).length===4,'math pipe signs must not split table columns');
check((html.match(/class="katex"/g)||[]).length===2,'table formulas should compile');
html=view.render('```latex\n\\frac{1}{\\theta^4}\n```\n\n```text\n<script>bad()</script> $literal$\n```');
check(html.includes('katex-display'),'explicit latex code block should display math');
check(html.includes('&lt;script&gt;bad()&lt;/script&gt; $literal$'),'ordinary code must remain escaped literal text');
check(!html.includes('<script>'),'code must not create scripts');
html=view.render('`$literal$` 与 $x^2$');
check(html.includes('<code>$literal$</code>'),'inline code remains literal');
check((html.match(/class="katex"/g)||[]).length===1,'inline code must not be interpreted as math');
html=view.render('<img src=x onerror=alert(1)>\n<script>bad()</script>\n\n[点我](javascript:alert(1))');
check(!html.includes('<img')&&!html.includes('<script'),'raw HTML must remain escaped');
check(!html.includes('href="javascript:')&&!html.includes('<a '),'arbitrary Markdown links must not become active links');
html=view.render('依据[E1]，对比[E9]。',{evidence:[{id:'E1',pages:[300]}]});
check(html.includes('data-page="300"')&&html.includes('E1 · PDF 300'),'known citations link to actual evidence');
check(html.includes('[E9]'),'unknown citations remain text');
html=view.render('依据[E1]。',{evidence:[{id:'E1',pages:[300]}],citationStyle:'link'});
check(html.includes('href="/library#page=300"'),'portfolio citation should link to local source');
html=view.render('[E1]',{evidence:[{id:'E1',pages:['x" onclick="alert(1)']}]});
check(!html.includes('data-page')&&!html.includes('<a '),'invalid page cannot create an attribute');
html=view.render('$[E1]$ 与 [E1]',{evidence:[{id:'E1',pages:[300]}]});
check((html.match(/data-page=/g)||[]).length===1,'citation linking must not modify formula contents');
html=view.render('$\\frac{1}{$');
check(html.includes('公式待校对'),'invalid math remains inspectable');
html=view.render('$\\href{https://example.com}{x}$');
check(html.includes('公式待校对')&&!html.includes('href="https:'),'unsafe math commands stay blocked');
html=view.render('\uE000ANSWER0\uE001\n\n> 来源待核对\n\n---');
check(html.includes('\uE000ANSWER0\uE001'),'input token lookalikes cannot substitute output tokens');
check(html.includes('<blockquote>')&&html.includes('<hr>'),'quotes and rules compile');
console.log(checks+' answer Markdown, math, source-link and injection checks passed');
