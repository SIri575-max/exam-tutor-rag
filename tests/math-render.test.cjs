const assert = require('node:assert/strict');
globalThis.katex = require('../assets/katex/katex.min.js');
const view = require('../math-render.js');
const source = String.raw`样本 x_{1},x_{2},\cdots,x_{n} 来自 U(0,\theta)`;
const a = source.indexOf('x_'), b = source.indexOf(' 来自');
view.register({text:source,_math:{text:[{start:a,end:b,display:false}]}});
assert(view.prose(source).includes('class="katex"'));
assert(view.formula(String.raw`\frac{1}{\theta^n}\prod_{i=1}^n I_{(0,\theta)}(x_i)`,true).includes('katex-display'));
assert(view.formula(String.raw`\overline{AB}`).includes('accent'));
assert(view.formula(String.raw`\sum_{i=1}^n(x_i-\mu)^2\tag{5.4.1}`,true).includes('tag'));
assert(view.formula(String.raw`\frac{1}{`).includes('公式待校对'));
assert(view.formula(String.raw`\href{https://example.com}{x}`).includes('公式待校对'));
assert(!view.prose('<img src=x onerror=alert(1)>').includes('<img'));
const delimited = '$x_1$';
view.register({text:delimited,_math:{text:[{start:1,end:4,display:false}]}});
assert.equal((view.prose(delimited).match(/class="katex"/g)||[]).length,1);
assert(!view.prose(delimited).includes('$'));
assert(view.segments([{type:'text',content:'设 '},{type:'equation_inline',content:'x_1'}]).includes('class="katex"'));
assert(view.segments(String.raw`\int_0^1 x\,dx`, 'equation').includes('katex-display'));
console.log('10 renderer checks passed');
