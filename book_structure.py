def location(page):
    data = structure()
    region = next((r for r in data['regions'] if r['pdf_first'] <= page <= r['pdf_last']), None)
    chapter = next((c for c in data['chapters'] if c['pdf_first'] <= page <= c['pdf_last']), None)
    section = None
    if chapter:
        candidates = [s for s in data['sections'] if s['chapter'] == chapter['id'] and s['pdf_first'] <= page]
        section = candidates[-1] if candidates else None
    return region, chapter, section
